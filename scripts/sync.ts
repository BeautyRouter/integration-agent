// Writes the generated parts of `plugin/`: the six Beauty Router skills and the logo, copied from the docs repository,
// and one Codex agent file per agent in `plugin/agents/`. With `--check`, it writes nothing and fails when a generated
// file is out of date, so CI can run it. It also fails when the three plugin manifests disagree on the version or the
// MCP server URL.
//
// Usage: node --experimental-strip-types scripts/sync.ts [--check] [--docs <path to the docs repository>]

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

type Files = Map<string, Buffer>;

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const plugin = join(root, "plugin");
const args = process.argv.slice(2);
const check = args.includes("--check");
const docsArg = args.indexOf("--docs");
const docs = resolve(docsArg >= 0 ? args[docsArg + 1] : join(root, "..", "docs"));

// The skills in the docs repository are their only source. The integrate skill is this repository's own.
const docsSkills = ["connect", "embed", "orders", "companies", "catalog", "webhooks"].map((s) => `beauty-router-${s}`);
const generatedDirs = [...docsSkills.map((s) => join(plugin, "skills", s)), join(plugin, "codex-agents")];

function readTree(dir: string, into: Files, target: string) {
  for (const name of readdirSync(dir)) {
    if (name === ".DS_Store") continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) readTree(path, into, join(target, name));
    else into.set(join(target, name), readFileSync(path));
  }
}

function frontmatter(text: string, file: string) {
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
  if (!match) throw new Error(`${file}: no frontmatter`);
  const fields = new Map<string, string>();
  for (const line of match[1].split("\n")) {
    const colon = line.indexOf(":");
    if (colon > 0) fields.set(line.slice(0, colon).trim(), line.slice(colon + 1).trim());
  }
  return { fields, body: match[2].trim() };
}

// Codex reads custom agents as TOML with `name`, `description`, and `developer_instructions`. The body goes in a
// literal string, which has no escapes, so it must not contain `'''`. Codex has no read-only setting per agent, because
// an agent file cannot override the sandbox, so `codexShellTool: false` in the frontmatter turns off the agent's shell
// instead, for an agent that needs none.
function codexAgent(file: string) {
  const { fields, body } = frontmatter(readFileSync(file, "utf8"), file);
  const name = fields.get("name");
  const description = fields.get("description");
  if (!name || !description) throw new Error(`${file}: name and description are required`);
  if (body.includes("'''")) throw new Error(`${file}: the body cannot contain '''`);
  return [
    `# Generated by scripts/sync.ts from plugin/agents/${name}.md. Edit that file, then run the sync.`,
    `name = ${JSON.stringify(name)}`,
    `description = ${JSON.stringify(description)}`,
    `developer_instructions = '''`,
    body,
    `'''`,
    ...(fields.get("codexShellTool") === "false" ? ["", "[features]", "shell_tool = false"] : []),
    "",
  ].join("\n");
}

function expected(): Files {
  if (!existsSync(join(docs, "public", "skills"))) throw new Error(`No skills in ${docs}. Pass --docs <path>.`);
  const files: Files = new Map();
  for (const skill of docsSkills) readTree(join(docs, "public", "skills", skill), files, join(plugin, "skills", skill));
  files.set(join(plugin, "assets", "logo.svg"), readFileSync(join(docs, "public", "beauty-router-mark.svg")));
  for (const name of readdirSync(join(plugin, "agents")).filter((n) => n.endsWith(".md"))) {
    const toml = codexAgent(join(plugin, "agents", name));
    files.set(join(plugin, "codex-agents", name.replace(/\.md$/, ".toml")), Buffer.from(toml));
  }
  return files;
}

function manifestProblems() {
  const read = (path: string) => JSON.parse(readFileSync(join(plugin, path), "utf8"));
  const versions = [".claude-plugin", ".cursor-plugin", ".codex-plugin"].map((d) => read(`${d}/plugin.json`).version);
  const problems = new Set(versions).size === 1 ? [] : [`The plugin manifests have different versions: ${versions}`];
  const claudeUrl = read(".claude-plugin/plugin.json").mcpServers["beauty-router"].url;
  const sharedUrl = read("mcp.json").mcpServers["beauty-router"].url;
  if (claudeUrl !== sharedUrl) problems.push(`The MCP URL differs: ${claudeUrl} and ${sharedUrl} in mcp.json`);
  return problems;
}

function existing(): Files {
  const files: Files = new Map();
  for (const dir of generatedDirs) if (existsSync(dir)) readTree(dir, files, dir);
  const logo = join(plugin, "assets", "logo.svg");
  if (existsSync(logo)) files.set(logo, readFileSync(logo));
  return files;
}

const want = expected();
const problems = manifestProblems();

if (check) {
  const have = existing();
  for (const [path, content] of want) {
    if (!have.get(path)?.equals(content)) problems.push(`Out of date: ${relative(root, path)}`);
  }
  for (const path of have.keys()) if (!want.has(path)) problems.push(`Not generated: ${relative(root, path)}`);
} else {
  for (const dir of generatedDirs) rmSync(dir, { recursive: true, force: true });
  for (const [path, content] of want) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}

if (problems.length) {
  console.error(problems.join("\n"));
  if (check) console.error("Run the sync without --check.");
  process.exit(1);
}
console.log(check ? "Generated files are up to date." : `Wrote ${want.size} files.`);
